import assert from 'node:assert/strict';
import { createServer } from 'vite';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
try {
 const {hydrateRequest,missingRequestFields,changeContent}=await server.ssrLoadModule('/src/domain/requestComposer.ts');
 const user={name:'담당자',email:'owner@example.invalid',phone:'010-1234-5678',organization:{name:'시험 기업'}};
 const original={applicant:{},test:{purpose:'진동 내구성 확인'},sample:{name:'위성 부품',quantity:1},schedule:{desiredStartDate:'2026-12-01',desiredEndDate:'2026-12-01'},conditions:[{key:'sample_mass',status:'UNCONFIRMED',value:15}],notes:''};
 const draft=hydrateRequest(original,user,'사용자가 설명한 시험조건');
 assert.equal(draft.applicant.companyName,user.organization.name);
 assert.equal(draft.actualUser.email,user.email);
 assert.deepEqual(draft.accounting,{});
 assert.equal(draft.conditions[0].status,'UNCONFIRMED');
 assert.equal(draft.notes,'사용자가 설명한 시험조건');
 assert.equal(original.applicant.companyName,undefined,'Source server content was mutated');
 const ready={...draft,accounting:{name:'회계 담당',email:'accounting@example.invalid'}};
 assert.deepEqual(missingRequestFields(ready),[]);
 assert(missingRequestFields(changeContent(ready,'test.purpose','   ')).some(f=>f.path==='test.purpose'));
 assert(missingRequestFields(changeContent(ready,'sample.quantity',0)).some(f=>f.path==='sample.quantity'));
 assert(missingRequestFields(changeContent(ready,'schedule.desiredEndDate','2026-11-30')).some(f=>f.path==='schedule.desiredEndDate'));
 assert(missingRequestFields(changeContent(ready,'schedule.desiredEndDate','2026-02-30')).length>0);
 assert(missingRequestFields(changeContent(ready,'accounting.email','not-an-email')).some(f=>f.path==='accounting.email'));
 const own={...ready,actualUser:{name:'실제 사용자',email:'actual@example.invalid'},notes:'직접 수정한 메모'};
 assert.deepEqual(hydrateRequest(own,user,'덮어쓸 수 없음').actualUser,own.actualUser);
 assert.equal(hydrateRequest(own,user,'덮어쓸 수 없음').notes,own.notes);
 const {createMockApi}=await server.ssrLoadModule('/src/demo/engine.ts');
 const {previewUsers}=await server.ssrLoadModule('/src/preview/user.ts');
 const api=createMockApi(); const company=previewUsers.company;
 const call=(method,url,body={})=>api.execute({method,url:'/api/v1'+url,body,user:company});
 const created=call('POST','/test-requests',{equipmentId:44});
 assert.equal(created.status,201);
 const id=created.envelope.data.id;
 const failed=call('POST',`/test-requests/${id}/submit`,{version:0});
 assert.equal(failed.status,400);
 assert(failed.envelope.error.details.missingItems.includes('accounting.name'));
 const {default:Progress}=await server.ssrLoadModule('/src/components/workflow/RequestProgressSummary.tsx');
 const summary={status:'CONFIRMED',revision:{content:ready},estimatedFee:{amount:0},result:{summary:'기관 등록 결과',reportNo:'REPORT-1',reportUrl:'javascript:alert(1)'},reservations:[{status:'CONFIRMED',startAt:'2026-12-01T00:00:00Z'}]};
 const html=renderToStaticMarkup(React.createElement(Progress,{request:summary}));
 assert(html.includes('0원 (예상)'));
 assert(html.includes('예약 확정')&&html.includes('기관 등록 결과'));
 assert(html.includes('납부·정산 상태는 아직 제공되지 않습니다.'));
 assert(!html.includes('href="javascript:'));
 const linked=renderToStaticMarkup(React.createElement(Progress,{request:{...summary,result:{...summary.result,reportUrl:'https://example.invalid/report'}}}));
 assert(linked.includes('href="https://example.invalid/report"'));
 console.log('PASS: known-data prefill without invented contacts, immutable edits, whitespace/date/email/quantity validation and DEMO submit guard');
 console.log('PASS: real-shaped fee/result summary, zero-fee handling, confirmed status and safe report links');
} finally { await server.close(); }
